function block(slot,name,purpose,role,context,evidence,detail){
  return [
    "[집값쓱 · 이미지 "+slot+" · "+name+"]",
    "- "+SHARED,
    "[이 이미지가 해야 할 일]",
    purpose,
    "[이 장면만의 제작 지시]",
    role,
    "[이번 글의 맥락]",
    context,
    "[사용자가 직접 입력한 원본·근거 메모 — 출처와 숫자는 별도 확인 필요]",
    evidence,
    "[작업 시작 전 판단]",
    detail
  ].join("\n\n");
}

