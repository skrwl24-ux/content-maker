function clean(value,max=15000){
  return typeof value==="string"?value.replace(/\r\n?/g,"\n").trim().slice(0,max):"";
}
function articleContext(title,body){
  const name=clean(title,250);
  const text=clean(body,10000);
  return [
    "[이번 글 — 원고 내용은 곧 사실 검증 완료를 뜻하지 않음]",
    "제목: "+(name||"제목 미입력"),
    "본문 발췌:\n"+(text||"본문 미입력"),
    clean(body).length>text.length?"(본문 일부만 전달됨. 생략된 부분의 수치·장면을 추측하지 말 것)":""
  ].filter(Boolean).join("\n");
}
