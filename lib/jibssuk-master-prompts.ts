export function buildJibssukImagePrompt(input: JibssukSceneInput) {
  const scene = JIBSSUK_SCENE_TEMPLATES[input.order - 1];
  if (!scene) throw new Error("집값쓱 장면은 1~7번만 지원합니다.");
  const sceneNarration = (input.narration || "").trim();
  const dataRows = (input.dataRows || "").trim();
  return [
    "[집값쓱 쇼츠 고품질 정보판 이미지 제작 — " + String(scene.order).padStart(2, "0") + "번 " + scene.title + "]",
    "",
    JIBSSUK_MASTER_STYLE,
    "",
    "[현재 장면 목적]",
    scene.goal,
    "",
    "[이번 장면 전용 바운더리 — 공통 절대 바운더리와 함께 준수]",
    scene.layout,
    "",
    "[주제]", input.projectTitle.trim() || "원문 자료의 핵심 주제",
    "[해당 장면 내레이션]", sceneNarration || "완성 대본의 해당 흐름을 근거로 장면 목적에 맞는 문구를 고르세요.",
    "[해당 장면 핵심 제목]", (input.headline || "").trim() || "원문에서 실제로 확인되는 짧은 제목을 생성하되 중요 정보는 유지하세요.",
    "[검증용 구조화 데이터]", dataRows || "별도 데이터행 없음. 원문의 수치를 확인하세요.",
    "",
    "[전체 완성 대본]", input.script.trim() || "(아직 입력 전: 실제 이미지 생성은 완성 대본을 입력한 뒤 진행)",
    "",
    "[원문 근거 자료]", input.rawContent.trim() || "(아직 입력 전: 실제 이미지 생성은 원문을 입력한 뒤 진행)",
    "",
    "[제작 전 마지막 확인]",
    "승인된 김포 마스터 참고 이미지를 이 요청과 함께 첨부했는지 확인하세요.",
    "지금은 위에서 지정한 " + scene.order + "번 장면의 투명 PNG 한 장만 제작하세요. 다른 장면이나 하단 자막은 넣지 마세요.",
    "최종 검수: 가로 X70~1010, 정보 요소 최하단 Y1320 위, Y1320~1920 RGBA 알파 0. 이 기준을 충족하지 않으면 제출 전에 다시 구성하세요.",
  ].join("\n");
}
